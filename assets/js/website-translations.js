// Apply translations to elements with data-website-translate attribute
// Initial apply (manager will also call this)
if (window.languageManager) {
  applyWebsiteTranslations(window.languageManager.getCurrentLanguage());
}

// Listen for language change events from language manager
window.addEventListener('languageChanged', function (e) {
  applyWebsiteTranslations(e.detail.language);
});

function applyWebsiteTranslations(lang) {
  // Get current language or use parameter if provided
  const currentLang = lang || document.documentElement.lang || 'en';

  // Apply translations to elements with data-website-translate attribute
  document.querySelectorAll('[data-website-translate]').forEach(el => {
    const key = el.getAttribute('data-website-translate');
    if (key && websiteTranslations[currentLang] && websiteTranslations[currentLang][key]) {
      const translation = websiteTranslations[currentLang][key];
      // Check if translation contains HTML tags
      if (/<[^>]+>/g.test(translation)) {
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  // Update page title if translation exists
  if (websiteTranslations[currentLang] && websiteTranslations[currentLang].pageTitle) {
    document.title = websiteTranslations[currentLang].pageTitle;
  }

  // Update document language attribute
  document.documentElement.lang = currentLang;
}

// Make translations and function available globally
window.websiteTranslations = websiteTranslations;
window.applyWebsiteTranslations = applyWebsiteTranslations;
